from Src.Core.base_entity import BaseEntity
from Src.Core.exception import ArgumentsException
from Src.Core.validator import Validator


class RangeModel(BaseEntity):
    """Модель единицы измерения.

    Хранит базовую единицу измерения и коэффициент пересчёта в неё.
    Базовая единица ссылается сама на себя и имеет коэффициент 1.
    Производная единица ссылается на базовую: килограмм — на грамм с коэффициентом 1000.

    Проектные решения:

    - ``base`` и ``factor`` задаются только в конструкторе и не имеют сеттеров.
      Они связаны инвариантом (у базовой единицы коэффициент всегда 1), поэтому раздельные
      сеттеры позволили бы его нарушить. Кроме того, смена базы или коэффициента
      молча изменила бы смысл всех единиц и номенклатуры, которые на них ссылаются.
      Нужна другая единица — создаётся новый экземпляр.
    - Базовая единица ссылается на себя, а не на ``None``: ``base`` всегда указывает
      на единицу, и проверять его на пустоту не нужно.
    - Базой может быть только базовая единица. Цепочки производных единиц не допускаются:
      тонна задаётся через грамм (1 000 000), а не через килограмм.
    """


    # Базовая единица измерения (у самой базовой единицы — она же)
    _base: "RangeModel"
    # Коэффициент пересчёта в базовую единицу
    _factor: int | float

    def __init__(self, name: str, factor: float, base: "RangeModel | None" = None) -> None:
        """Инициализирует единицу измерения.

        :param name: Наименование единицы измерения.
        :param factor: Коэффициент пересчёта в базовую единицу, число больше нуля.
        :param base: Базовая единица измерения. Если не указана, создаваемая единица
            сама является базовой, и её коэффициент должен быть равен 1.
        :raises ArgumentsException: Если наименование некорректно, коэффициент не является
            положительным конечным числом, у базовой единицы коэффициент не равен 1,
            base не является единицей измерения или не является базовой единицей.
        """
        super().__init__(name)
        factor = Validator.validate_positive_number(factor, "factor")

        if base is None:
            if factor != 1:
                raise ArgumentsException("factor", "У базовой единицы коэффициент пересчёта должен быть равен 1")
            base = self
        else:
            base = Validator.validate_instance(base, RangeModel, "base", "Ожидается единица измерения")
            if not base.is_base:
                raise ArgumentsException("base", "В качестве базовой можно указать только базовую единицу измерения")

        self._base = base
        self._factor = factor


    @property
    def base(self) -> "RangeModel":
        """Возвращает базовую единицу измерения (для базовой единицы — её саму).

        Только для чтения: задаётся в конструкторе.
        """
        return self._base

    @property
    def factor(self) -> int | float:
        """Возвращает коэффициент пересчёта в базовую единицу.

        Только для чтения: задаётся в конструкторе.
        """
        return self._factor

    @property
    def is_base(self) -> bool:
        """Возвращает True, если единица измерения является базовой."""
        return self._base is self
