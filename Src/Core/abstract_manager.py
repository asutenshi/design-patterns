from abc import ABC, abstractmethod


class AbstractManager(ABC):
    """Базовый класс менеджеров: общий контракт загрузки.

    Знает только о флаге загрузки и о том, что менеджер умеет load(). Откуда берутся
    данные (файл, БД, ничего), решают наследники. Singleton базовый класс не реализует:
    каждый конкретный менеджер делает это в своём __new__ и вызывает _initialize()
    при первом создании.
    """

    # Флаг. Загрузка и обработка завершена успешно
    _is_loaded: bool

    def _initialize(self) -> None:
        """Хук: готовит состояние менеджера при первом создании экземпляра.

        Конкретный __new__ вызывает его один раз, до сохранения экземпляра.
        Наследники, добавляющие своё состояние, обязаны вызывать super()._initialize().
        Обращаться к другим менеджерам из хука нельзя, такие зависимости
        разрешаются в load().
        """
        self._is_loaded = False

    @abstractmethod
    def load(self) -> None:
        """Загружает данные менеджера.

        Реализация сбрасывает is_loaded в начале и выставляет True только в конце,
        после успеха. Наследник может добавить необязательные параметры.

        :raises OperationException: Если данные не удалось загрузить.
        """

    @property
    def is_loaded(self) -> bool:
        """Возвращает True, если загрузка завершена успешно."""
        return self._is_loaded
