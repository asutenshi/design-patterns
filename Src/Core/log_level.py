from enum import Enum


class LogLevel(Enum):
    """Уровень важности записи лога.

    Значения — строки в верхнем регистре: в таком виде тип сообщения попадает в лог,
    выгрузки и условия фильтрации API.
    """

    # Отладочная информация
    DEBUG = "DEBUG"
    # Информационное сообщение о штатной операции
    INFO = "INFO"
    # Сообщение об ошибке
    ERROR = "ERROR"
