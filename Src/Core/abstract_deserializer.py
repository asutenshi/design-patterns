from abc import ABC, abstractmethod


class AbstractDeserializer(ABC):
    """Абстрактный десериализатор: превращает значение из JSON обратно в объект.

    Это обратная сторона ``AbstractConverter``. У каждого вида значений JSON свой наследник: модель
    (словарь с ``model_type`` или ссылка ``{"id": ...}``), список, простое значение. Наследника выбирает
    по виду значения фабрика ``DeserializerFactory``, клиент работает только с ней.

    О конкретных моделях десериализаторы не знают: модель создаёт себя сама (``AbstractModel.from_dict``).
    Поэтому новая модель подключается только своим ``from_dict``, без нового десериализатора.
    Вложенные значения наследник собирает через функцию фабрики, это и есть рекурсия.
    """

    @abstractmethod
    def deserialize(self, data: object) -> object:
        """Превращает значение из JSON в объект.

        :param data: Значение, как его вернул ``json.load``.
        :return: Объект: модель, список объектов или простое значение.
        :raises ArgumentsException: Если значение не подходит этому десериализатору или модель не собралась.
        :raises OperationException: Если в данных ссылка на модель, которой нет в данных.
        """
