from enum import Enum


class NomenclatureType(Enum):
    """Тип позиции номенклатуры (п. 1.1 ТЗ)."""

    # Сырьё: закупается и используется в производстве
    RAW_MATERIAL = "сырьё"
    # Товар: закупается и продаётся без переработки
    PRODUCT = "товар"
    # Полуфабрикат: готовится по технологической карте, входит в состав блюд
    SEMI_FINISHED = "полуфабрикат"
    # Блюдо: готовится по технологической карте, продаётся
    DISH = "блюдо"
    # Упаковка
    PACKAGING = "упаковка"
